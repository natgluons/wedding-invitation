import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFileSync} from 'node:fs';
import worker,{sha256,validateSnapshot} from '../validation-worker/src.mjs';
const sqlite=new DatabaseSync(':memory:');
sqlite.exec(readFileSync(new URL('../validation-worker/schema.sql',import.meta.url),'utf8'));
const wrap=(sql,args=[])=>({sql,args,bind(...values){return wrap(sql,values)},async first(){return sqlite.prepare(sql).get(...args)||null}});
const env={SYNC_SECRET:'test-only-secret',MAX_SYNC_AGE_SECONDS:'900',DB:{prepare:sql=>wrap(sql),async batch(statements){sqlite.exec('BEGIN');try{for(const {sql,args}of statements)sqlite.prepare(sql).run(...args);sqlite.exec('COMMIT');}catch(error){sqlite.exec('ROLLBACK');throw error;}}}};
const call=(path,body,auth)=>worker.fetch(new Request('https://test.invalid'+path,{method:body===undefined?'GET':'POST',headers:{'Content-Type':'text/plain',...(auth?{Authorization:'Bearer '+auth}:{})},body:body===undefined?undefined:JSON.stringify(body)}),env);
const code='TESTCODE123',other='OTHER12345';
assert.equal((await call('/health')).status,200);
assert.equal((await call('/validate',{code})).status,503,'unseeded database must be unavailable, not invalid');
assert.equal((await call('/validate',{code:'short'})).status,400);
const guests=[{codeHash:await sha256(code),name:'Guest & Family',maxGuests:4,revoked:false},{codeHash:await sha256(other),name:'Revoked',maxGuests:2,revoked:true}];
assert.throws(()=>validateSnapshot({version:1,guests:[guests[0],guests[0]]}));
assert.equal((await call('/sync',{version:100,guests})).status,401);
assert.equal((await call('/sync',{version:100,guests},env.SYNC_SECRET)).status,200);
let response=await call('/validate',{code});
assert.deepEqual(await response.json(),{ok:true,guest:{name:'Guest & Family',maxGuests:4}});
assert.equal(response.headers.get('Access-Control-Allow-Origin'),'*');
assert.equal(response.headers.get('Cache-Control'),'no-store');
assert.equal((await call('/validate',{code:other})).status,403);
assert.equal((await call('/validate',{code:'UNKNOWN123'})).status,403);
assert.equal((await call('/sync',{version:99,guests:[]},env.SYNC_SECRET)).status,409);
assert.equal((await call('/validate',{code})).status,200,'stale push cannot wipe newer data');
assert.equal((await call('/sync',{version:101,guests:[{...guests[0],revoked:true}]},env.SYNC_SECRET)).status,200);
assert.equal((await call('/validate',{code})).status,403,'revocation applies on the next sync');
assert.equal(sqlite.prepare('SELECT count(*) AS n FROM guests').get().n,1,'snapshot removes deleted invitations');
sqlite.prepare('UPDATE sync_state SET synced_at=?').run(Date.now()-901000);
assert.equal((await call('/validate',{code})).status,503,'stale mirror must fall back to sheet validation');
assert.equal((await call('/sync',{version:102,guests:[]},env.SYNC_SECRET)).status,200);
assert.equal((await call('/validate',{code})).status,403,'an intentionally empty synced list rejects codes');
console.log('Worker checks passed: initialization, authorized atomic sync, hashes, code validation, revocation, deletion, stale sync protection and CORS.');
sqlite.close();
